#!/usr/bin/env node
// Pulls the public DataPopcorn analysis skills from GitHub and writes skills-bundle.js,
// which the Worker imports. Re-run this, then `npx wrangler deploy`, whenever the skills change.
//   node scripts/sync-skills.mjs            # from GitHub main (default, the source of truth)
//   node scripts/sync-skills.mjs --local ~/.aside/u/0/skills/user   # from a local skills folder
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO = "team-datapopcorn/datapopcorn-analysis-plugin";
const REF = "main";
const FILES = [
  ["data-analysis-pipeline", "SKILL.md", "text/markdown"],
  ["1-hypothesis", "SKILL.md", "text/markdown"],
  ["2-collect", "SKILL.md", "text/markdown"],
  ["2-collect", "references/data-sources-korea.md", "text/markdown"],
  ["3-suspect", "SKILL.md", "text/markdown"],
  ["3-suspect", "references/trend-traps.md", "text/markdown"],
  ["4-report", "SKILL.md", "text/markdown"],
  ["4-report", "assets/template.html", "text/html"],
  ["4-report", "scripts/inline_assets.py", "text/x-python"],
];

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.join(here, "..", "skills-bundle.js");
const localIdx = process.argv.indexOf("--local");
const localRoot = localIdx > -1 ? process.argv[localIdx + 1].replace(/^~/, process.env.HOME) : null;

async function read(skill, file) {
  if (localRoot) return fs.readFileSync(path.join(localRoot, skill, file), "utf8");
  const url = `https://raw.githubusercontent.com/${REPO}/${REF}/skills/${skill}/${file}`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url} -> HTTP ${res.status}`);
  return res.text();
}

const entries = [];
for (const [skill, file, mimeType] of FILES) {
  const text = await read(skill, file);
  entries.push({ skill, file, mimeType, uri: `datapopcorn://skills/${skill}/${file}`, text });
}

const header = `// AUTO-GENERATED by scripts/sync-skills.mjs from ${localRoot ? "local " + localRoot : `github.com/${REPO}@${REF}`} at ${new Date().toISOString()}. Do not edit by hand.\n`;
fs.writeFileSync(out, header + `export const SKILL_SOURCE = ${JSON.stringify(localRoot ? "local" : `github.com/${REPO}@${REF}`)};\nexport const SKILL_FILES = ${JSON.stringify(entries, null, 1)};\n`);
console.log(`wrote ${out}: ${entries.length} files, ${entries.reduce((n, e) => n + e.text.length, 0)} chars`);
